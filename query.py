#Extração de dados da planilah de contratação.

CONTRATACAO = """SELECT
    R.CODRQU AS "REQUISICAO",
    R.NUMEMP AS "COD_EMPRESA",
    E.NOMEMP AS "EMPRESA_REQUISITANTE",
    R.CODFIL AS "COD_FILIAL",
    F.NOMFIL AS "FILIAL",

    R.TABORG AS "TABELA_ORGANOGRAMA",
    R.NUMLOC AS "COD_LOCAL",
    L.NOMLOC AS "LOCAL_SETOR",

    R.DATRQU AS "DATA_REQUISICAO",
    R.QTDRQU AS "QTD_VAGAS",

    -- MOTIVO / TIPO DA ABERTURA
    R.TIPRQU AS "COD_TIPO_REQUISICAO",
    A.CODRRQ AS "COD_DESCRICAO",
    A.DESRRQ AS "DESCRICAO_SUBSTUICAO",

    R.TIPCOL AS "TIPO_COLAB_SOLICITANTE",
    R.NUMCAD AS "MATRICULA_SOLICITANTE",
    R.DATAPR AS "DATA_APROVACAO",
    R.SITRQU AS "COD_SITUACAO_REQUISICAO",
    R.DATENC AS "DATA_ENCERRAMENTO",
    R.TIPVAG AS "COD_TIPO_VAGA",
    R.ORIRQU AS "COD_ORIGEM_REQUISICAO",
    R.IDEEXT AS "IDENTIFICADOR_EXTERNO"

FROM R126RQU R

LEFT JOIN R030EMP E
    ON E.NUMEMP = R.NUMEMP

LEFT JOIN R030FIL F
    ON F.NUMEMP = R.NUMEMP
   AND F.CODFIL = R.CODFIL

LEFT JOIN R016ORN L
    ON L.TABORG = R.TABORG
   AND L.NUMLOC = R.NUMLOC

LEFT JOIN R114RRQ A
ON R.TIPRQU = A.CODRRQ 

WHERE R.DATRQU >= TO_DATE('01/01/2026', 'DD/MM/YYYY')
AND R.TIPCOL = '1'

ORDER BY R.DATRQU DESC, R.CODRQU DESC"""